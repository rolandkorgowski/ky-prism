#!/usr/bin/env python3
"""Compile our reviewed UTF-8 catalog into C++; no runtime files or Linguist dependency."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
PUBLIC_HEADER='// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 Krzysztof Kylen Lenartowicz\n'
def canonical_content(data):
    return data.removeprefix(PUBLIC_HEADER)
def generated():
    rows=json.loads((ROOT/'i18n/en.json').read_text())
    import re
    for source,target in rows.items():
        if sorted(re.findall(r'%\d+',source))!=sorted(re.findall(r'%\d+',target)):
            raise ValueError('Changed translation placeholders: '+source)
    body='// Generated by i18n/generate.py; edit i18n/en.json.\n#pragma once\n#include <QHash>\n#include <QString>\ninline const QHash<QString,QString> &prismEnglishCatalog() {\n  static const QHash<QString,QString> data{\n'
    for source,target in rows.items():
        body+='    {QString::fromUtf8('+json.dumps(source,ensure_ascii=False)+'),QString::fromUtf8('+json.dumps(target,ensure_ascii=False)+')},\n'
    return '// Copyright (c) 2026 Krzysztof Kylen Lenartowicz\n'+body+'  };\n  return data;\n}\n'
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    target=ROOT/'src/language_catalog.h';data=generated()
    if args.check:
        if not target.is_file() or canonical_content(target.read_text())!=data:raise SystemExit('Stale language catalog; run python3 i18n/generate.py')
    else:target.write_text(data)
